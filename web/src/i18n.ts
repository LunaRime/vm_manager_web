export const LANGUAGES: Language[] = ['zh-CN', 'zh-TW', 'en'];

export function t(key: string, lang: Language): string {
  const row = D[key];
  if (!row) return key;
  const index = lang === 'en' ? 2 : lang === 'zh-TW' ? 1 : 0;
  const parts = row.split('|');
  return parts[index] || parts[0];
}

export function formatTime(ts: number, lang: Language): string {
  if (!ts) return '--';
  const locale = lang === 'en' ? 'en-US' : lang === 'zh-TW' ? 'zh-TW' : 'zh-CN';
  return new Date(ts).toLocaleString(locale, { hour12: false });
}

export function formatSize(mb: number): string {
  if (!Number.isFinite(mb)) return '--';
  return mb >= 1024 ? `${(mb / 1024).toFixed(2)} GB` : `${mb.toFixed(1)} MB`;
}
